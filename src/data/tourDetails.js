/*
 * Keep the original numeric object structure because other
 * parts of the website may still access:
 *
 * tourDetails[1]
 * tourDetails[2]
 * etc.
 */

const allTours = Object.values(tourDetails);

/*
 * Find a tour safely using its public URL slug.
 *
 * Examples:
 * getTourBySlug("masai-mara-safari")
 * getTourBySlug("MASAI-MARA-SAFARI")
 */
export const getTourBySlug = (slug) => {
  if (!slug) return null;

  const normalizedSlug = String(slug)
    .trim()
    .toLowerCase();

  return (
    allTours.find(
      (tour) =>
        String(tour.slug).trim().toLowerCase() ===
        normalizedSlug
    ) || null
  );
};

/*
 * Find a tour using either:
 *
 * - numeric ID
 * - string ID
 * - public slug
 */
export const getTour = (identifier) => {
  if (
    identifier === undefined ||
    identifier === null ||
    identifier === ""
  ) {
    return null;
  }

  const value = String(identifier).trim();

  // Try slug first
  const slugMatch = getTourBySlug(value);

  if (slugMatch) {
    return slugMatch;
  }

  // Then try numeric ID
  const numericId = Number(value);

  if (!Number.isNaN(numericId)) {
    return tourDetails[numericId] || null;
  }

  return null;
};

/*
 * Convenient array for Tours page / filters.
 */
export const tours = allTours;

